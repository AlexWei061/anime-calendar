import { createHash } from "node:crypto";
import { access, copyFile, link, mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

const cellWidth = 600;
const cellHeight = 750;
const thumbnailCellWidth = cellWidth / 2;
const thumbnailCellHeight = cellHeight / 2;
const columns = 4;
const rows = 10;
const coversPerSprite = columns * rows;

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return false;
  }
}

function mappingSource(sprites) {
  return "// Generated by scripts/generate-cover-sprites.mjs.\n" +
    "export const coverSprites = Object.freeze(" + JSON.stringify(sprites, null, 2) + ");\n\n" +
    "export function coverSpriteFor(coverUrl, variant = \"thumbnail\") {\n" +
    "  const sprite = coverSprites[coverUrl] ?? null;\n" +
    "  if (!sprite || variant === \"detail\") return sprite;\n" +
    "  return { ...sprite, url: sprite.url.replace(/\\.webp$/, \"-thumb.webp\") };\n" +
    "}\n";
}

export async function generateCoverSprites({ projectRoot, anime, previousSprites }) {
  const localPath = (url) => {
    if (!url.startsWith("/covers/yuc/") || url.split("/").includes("..")) {
      throw new Error(`Invalid local cover URL: ${url}`);
    }
    return join(projectRoot, "public", url.slice(1));
  };
  const covers = [...anime].sort(({ coverUrl: left }, { coverUrl: right }) => left.localeCompare(right));
  if (!covers.length || new Set(covers.map(({ coverUrl }) => coverUrl)).size !== covers.length) {
    throw new Error("Each anime needs a unique cover URL before generating sprites.");
  }
  const spriteDirectory = join(projectRoot, "public/covers/yuc/sprites");
  await mkdir(spriteDirectory, { recursive: true });
  const staged = await mkdtemp(join(projectRoot, ".cover-sprites-"));
  const sprites = {};
  const standaloneFiles = new Set();
  const stagedFiles = new Map();
  const createdFiles = [];
  let published = false;

  try {
    for (let offset = 0; offset < covers.length; offset += coversPerSprite) {
      const page = covers.slice(offset, offset + coversPerSprite);
      const spriteRows = Math.ceil(page.length / columns);
      const detailPath = join(staged, `detail-${offset}.webp`);
      const thumbnailPath = join(staged, `thumbnail-${offset}.webp`);
      const originals = [];
      for (const { coverUrl } of page) {
        if (coverUrl.startsWith("/covers/yuc/sprites/")) throw new Error(`Expected a logical cover URL: ${coverUrl}`);
        const path = localPath(coverUrl);
        originals.push(await exists(path));
        if (originals.at(-1)) standaloneFiles.add(path);
      }
      const oldPage = previousSprites[page[0].coverUrl];
      const unchanged = originals.every((present) => !present) && page.every(({ coverUrl }, index) => {
        const old = previousSprites[coverUrl];
        return old && old.url === oldPage?.url && old.columns === columns && old.rows === spriteRows &&
          old.x === index % columns && old.y === Math.floor(index / columns);
      });

      if (unchanged) {
        // Repeated runs keep the exact bytes instead of recompressing lossy WebP.
        await copyFile(localPath(oldPage.url), detailPath);
        await copyFile(localPath(oldPage.url.replace(/\.webp$/, "-thumb.webp")), thumbnailPath);
      } else {
        const composite = [];
        for (const [index, { coverUrl }] of page.entries()) {
          let input;
          if (originals[index]) {
            input = sharp(localPath(coverUrl)).resize(cellWidth, cellHeight, { fit: "cover" });
          } else {
            const old = previousSprites[coverUrl];
            if (!old) throw new Error(`Missing cover input and previous sprite: ${coverUrl}`);
            input = sharp(localPath(old.url)).extract({
              left: old.x * cellWidth, top: old.y * cellHeight, width: cellWidth, height: cellHeight,
            });
          }
          composite.push({
            input: await input.png().toBuffer(),
            left: (index % columns) * cellWidth,
            top: Math.floor(index / columns) * cellHeight,
          });
        }
        await sharp({
          create: { width: columns * cellWidth, height: spriteRows * cellHeight, channels: 4,
            background: { r: 255, g: 255, b: 255, alpha: 0 } },
        }).composite(composite).webp({ quality: 90, effort: 4 }).toFile(detailPath);
        await sharp(detailPath)
          .resize(columns * thumbnailCellWidth, spriteRows * thumbnailCellHeight)
          .webp({ quality: 82, effort: 4 }).toFile(thumbnailPath);
      }

      // New assets never overwrite files used by the current mapping. Keep the
      // existing numeric filename shape while addressing both variants by content.
      const hash = createHash("sha256").update(await readFile(detailPath)).update(await readFile(thumbnailPath)).digest("hex");
      const spriteUrl = `/covers/yuc/sprites/cover-sheet-${BigInt(`0x${hash}`)}.webp`;
      stagedFiles.set(localPath(spriteUrl), detailPath);
      stagedFiles.set(localPath(spriteUrl.replace(/\.webp$/, "-thumb.webp")), thumbnailPath);
      for (const [index, { coverUrl }] of page.entries()) {
        sprites[coverUrl] = { url: spriteUrl, x: index % columns, y: Math.floor(index / columns), columns, rows: spriteRows };
      }
    }

    const stagedMapping = join(staged, "cover-sprites.js");
    await writeFile(stagedMapping, mappingSource(sprites));
    for (const [target, source] of stagedFiles) {
      try {
        await link(source, target);
        createdFiles.push(target);
      } catch (error) {
        if (error.code !== "EEXIST") throw error;
      }
    }
    await rename(stagedMapping, join(projectRoot, "data/cover-sprites.js"));
    published = true;

    const obsoleteFiles = new Set(Object.values(previousSprites).flatMap(({ url }) =>
      [localPath(url), localPath(url.replace(/\.webp$/, "-thumb.webp"))]));
    for (const path of [...obsoleteFiles, ...standaloneFiles]) {
      if (stagedFiles.has(path)) continue;
      await rm(path, { force: true }).catch((error) => console.warn(`Cover published; could not remove ${path}: ${error.message}`));
    }
    return sprites;
  } finally {
    if (!published) await Promise.all(createdFiles.map((path) => rm(path, { force: true })));
    await rm(staged, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [{ allAnime }, { coverSprites }] = await Promise.all([
    import("../data/anime.js"), import("../data/cover-sprites.js"),
  ]);
  await generateCoverSprites({
    projectRoot: dirname(dirname(fileURLToPath(import.meta.url))), anime: allAnime, previousSprites: coverSprites,
  });
  console.log(`Packed ${allAnime.length} covers into ${Math.ceil(allAnime.length / coversPerSprite)} WebP sprites.`);
}

// 客户端精简目录生成器：从 data/anime.js 的完整目录（含 *Source 等审计字段）推导
// data/catalog-client.js——只保留前端实际消费的字段，供 app/catalog.ts 引用；
// 完整审计数据继续留在 data/anime.js 与其引用的生成数据文件中，不进入客户端 bundle。
// 同步性由 tests/catalog-maintenance.test.mjs 保证（重新推导并与提交文件逐字段比对）。
//
// 用法：node scripts/generate-catalog-client.mjs [--verify]
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile, rename, rm, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

import { seasons } from "../data/anime.js";

// 前端消费的 Anime 字段（实证：app/ 与前端引用的 lib/ 的属性访问；见任务报告）。
const CLIENT_ANIME_FIELDS = [
  "id",
  "titleZh",
  "titleJa",
  "coverUrl",
  "coverAlt",
  "episodeCount",
  "episodeCountStatus",
  "premiereDateBeijing",
  "scheduleWeekday",
  "beijingTime",
  "station",
  "sourceUrl",
  "premiereKind",
  "premiereEpisodeCount",
  "regularBroadcastStartDateBeijing",
  "episodeSchedules",
  "scheduleChannel",
];

// 前端消费的 Season 字段（timelineStartHour 仅测试引用，不下发）。
const CLIENT_SEASON_FIELDS = [
  "id",
  "firstWeekStart",
  "label",
  "timeZoneLabel",
  "updatedAt",
  "catalogCount",
  "sourceName",
  "sourceUrl",
];

// 已知但不下发的审计字段。目录出现未登记的新字段时必须在这里或上表显式归类。
const AUDIT_ONLY_ANIME_FIELDS = new Set([
  "anilistId",
  "yucSourceId",
  "yucSourceUrl",
  "yucCoverUrl",
  "timeStatus",
  "titleSource",
  "coverSource",
  "stationSource",
  "episodeCountSource",
  "premiereDateSource",
  "scheduleWeekdaySource",
  "beijingTimeSource",
  "premiereEpisodeCountSource",
  "regularBroadcastStartDateSource",
  "episodeSchedulesSource",
  "scheduleSourceName",
  "scheduleSourceUrl",
]);

const clientAnimeFieldSet = new Set(CLIENT_ANIME_FIELDS);

export function clientAnimeRecord(record) {
  for (const key of Object.keys(record)) {
    if (!clientAnimeFieldSet.has(key) && !AUDIT_ONLY_ANIME_FIELDS.has(key)) {
      throw new Error(`目录出现未归类字段 ${key}（${record.id}）；请确认前端是否消费后更新 CLIENT_ANIME_FIELDS 或 AUDIT_ONLY_ANIME_FIELDS`);
    }
  }
  const slim = {};
  for (const field of CLIENT_ANIME_FIELDS) {
    if (record[field] !== undefined) slim[field] = record[field];
  }
  return slim;
}

const KNOWN_SEASON_FIELDS = new Set([...CLIENT_SEASON_FIELDS, "anime", "timelineStartHour"]);

export function clientCatalogFrom(sourceSeasons) {
  return {
    seasons: sourceSeasons.map((season) => {
      for (const key of Object.keys(season)) {
        if (!KNOWN_SEASON_FIELDS.has(key)) {
          throw new Error(`季度出现未归类字段 ${key}（${season.id}）；请更新 generate-catalog-client.mjs 的字段表`);
        }
      }
      const slim = {};
      for (const field of CLIENT_SEASON_FIELDS) slim[field] = season[field];
      slim.anime = season.anime.map(clientAnimeRecord);
      return slim;
    }),
  };
}

function renderClientCatalog({ seasons: clientSeasons }) {
  return `// Generated by scripts/generate-catalog-client.mjs. Do not edit by hand.
// 前端实际消费字段的精简目录；审计字段保留在 data/anime.js 与各生成数据文件中，不下发客户端。

export const seasons = ${JSON.stringify(clientSeasons, null, 2)};

export const allAnime = seasons.flatMap(({ anime }) => anime);
`;
}

const clientDeclaration = `// Generated by scripts/generate-catalog-client.mjs. Do not edit by hand.
import type { Anime, Season } from "../app/types";

export declare const seasons: Season[];
export declare const allAnime: Anime[];
`;

async function writeAtomically(relativePath, content) {
  const target = new URL(`../${relativePath}`, import.meta.url);
  const staged = new URL(`../data/.catalog-client-${randomUUID()}.tmp`, import.meta.url);
  try {
    await writeFile(staged, content);
    await rename(staged, target);
  } finally {
    await rm(staged, { force: true });
  }
}

async function main() {
  const verify = process.argv.includes("--verify");
  const generated = renderClientCatalog(clientCatalogFrom(seasons));
  const catalogPath = new URL("../data/catalog-client.js", import.meta.url);
  const declarationPath = new URL("../data/catalog-client.d.ts", import.meta.url);
  if (verify) {
    assert.equal(await readFile(catalogPath, "utf8"), generated, "data/catalog-client.js 与完整目录推导结果不一致；请运行 npm run generate:catalog-client");
    assert.equal(await readFile(declarationPath, "utf8"), clientDeclaration, "data/catalog-client.d.ts 与生成器输出不一致");
    console.log("verify OK: data/catalog-client.js 与 data/anime.js 推导结果逐字段一致");
    return;
  }
  await writeAtomically("data/catalog-client.js", generated);
  await writeAtomically("data/catalog-client.d.ts", clientDeclaration);
  console.log(`wrote data/catalog-client.js（${seasons.length} 季）与 data/catalog-client.d.ts`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
